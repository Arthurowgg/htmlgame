# Normalize fancy punctuation before lookup
_TRANS = str.maketrans({
    "\u00b7": "·", "\u2022": "•", "\u2013": "-", "\u2014": "-",
    "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
    "\u2026": "...", "\xa0": " ",
})


def measure(text: str, scale: int = 1) -> int:
    if not text:
        return 0
    s = str(text).translate(_TRANS)
    return len(s) * (FONT_W + FONT_GAP) * scale - FONT_GAP * scale


def draw_text(surf, text, x, y, color=None, scale: int = 1, shadow=False, shadow_color=None, align="left"):
    """Draw pixel text onto a pygame Surface. Coordinates in surface pixels."""
    import pygame
    if color is None:
        color = C["text"]
    s = str(text).translate(_TRANS)
    w = measure(s, scale)
    if align == "center":
        x = x - w // 2
    elif align == "right":
        x = x - w
    cx = int(x)
    cy = int(y)
    for ch in s:
        glyph = _G.get(ch) or _G.get(ch.upper()) or _G.get(ch.lower()) or _G["?"]
        if shadow:
            sc = shadow_color or C["shadow"]
            _blit_glyph(surf, glyph, cx + scale, cy + scale, sc, scale)
        _blit_glyph(surf, glyph, cx, cy, color, scale)
        cx += (FONT_W + FONT_GAP) * scale
    return w


def _blit_glyph(surf, glyph, x, y, color, scale):
    import pygame
    px = pygame.Rect(0, 0, scale, scale)
    for row, bits in enumerate(glyph):
        for col, bit in enumerate(bits):
            if bit == "1":
                px.topleft = (x + col * scale, y + row * scale)
                surf.fill(color, px)
